#!/usr/bin/env python3
"""Generate Wazuh credentials BEFORE first boot, so upstream's published defaults are never live. Stdlib only.

  python3 scripts/gen_secrets.py            # run by scripts/bootstrap.sh

1. Fills any empty secret in .env with a random value (file kept at 0600). Values are never printed.
2. Writes data/wazuh/internal_users.yml: admin + kibanaserver with fresh bcrypt hashes, plus cc_reader for the CC
   API and the triage agent (no backend roles; scripts/indexer_roles.py maps it to the read-only role cc_read). Upstream's other demo users (kibanaro, logstash,
   readall, snapshotrestore: published hashes) are dropped.
3. Writes data/wazuh/wazuh.yml (dashboard -> Wazuh API connection) with the generated API password. Upstream mounts
   a wazuh.yml that already holds the default password, which makes the dashboard skip its own templating.

The indexer applies internal_users.yml only when it initialises its security index, i.e. on a FRESH volume.
Changing passwords on an existing deployment needs securityadmin; see HANDOFF.md.
Bcrypt hashing uses the natively installed wazuh-indexer's own hash.sh (-env: the password is passed by environment,
never argv). No container runtime is involved (the project does not use Docker). Pure renderers are unit-tested in
tests/test_stack.py.
"""
from __future__ import annotations

import os
import pathlib
import re
import secrets
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"
OUT = ROOT / "data" / "wazuh"
HASH_TOOL = os.environ.get("CC_HASH_TOOL", "/usr/share/wazuh-indexer/plugins/opensearch-security/tools/hash.sh")
INDEXER_JDK = os.environ.get("CC_INDEXER_JDK", "/usr/share/wazuh-indexer/jdk")

# .env key -> role. INDEXER_USER/INDEXER_PASS are what the CC API and triage agent use (cc_reader).
SECRETS = ("WAZUH_ADMIN_PASS", "WAZUH_KIBANASERVER_PASS", "WAZUH_API_PASS", "INDEXER_PASS")
CC_READER = "cc_reader"
SAFE = re.compile(r"^[A-Za-z0-9_.\-]{16,64}$")   # no quoting/escaping hazards in YAML or compose interpolation


def new_password() -> str:
    """Random, and satisfies the Wazuh API policy (8-64 chars, upper, lower, digit, symbol)."""
    return secrets.token_urlsafe(24)[:28] + "Aa1."


def parse_env(text: str) -> dict[str, str]:
    out = {}
    for ln in text.splitlines():
        s = ln.strip()
        if s and not s.startswith("#") and "=" in s:
            k, v = s.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def fill_env(text: str, gen=new_password) -> tuple[str, list[str]]:
    """Pure: set every empty SECRETS key (or append it); force INDEXER_USER=cc_reader. Returns (text, keys_set)."""
    lines, seen, changed = text.splitlines(), set(), []
    for i, ln in enumerate(lines):
        if "=" not in ln or ln.lstrip().startswith("#"):
            continue
        k, v = ln.split("=", 1)
        k = k.strip()
        seen.add(k)
        if k in SECRETS and not v.strip():
            lines[i] = f"{k}={gen()}"
            changed.append(k)
        elif k == "INDEXER_USER" and v.strip() != CC_READER:
            lines[i] = f"INDEXER_USER={CC_READER}"
            changed.append(k)
    for k in SECRETS:
        if k not in seen:
            lines.append(f"{k}={gen()}")
            changed.append(k)
    if "INDEXER_USER" not in seen:
        lines.append(f"INDEXER_USER={CC_READER}")
        changed.append("INDEXER_USER")
    return "\n".join(lines) + "\n", changed


def check_secret(name: str, value: str) -> None:
    if value in ("SecretPassword", "kibanaserver", "MyS3cr37P450r.*-", "wazuh-wui"):
        raise ValueError(f"{name} is an upstream default; clear it in .env and re-run to generate one")
    if not SAFE.match(value):
        raise ValueError(f"{name} must be 16-64 chars of [A-Za-z0-9_.-] (generated values always are)")


def render_internal_users(hashes: dict[str, str]) -> str:
    """Pure: OpenSearch security internal_users.yml with only the users this deployment needs."""
    for u in ("admin", "kibanaserver", CC_READER):
        h = hashes[u]
        if not re.match(r"^\$2[aby]\$\d\d\$[./A-Za-z0-9]{53}$", h):
            raise ValueError(f"not a bcrypt hash for {u}")
    return f"""---
# GENERATED by scripts/gen_secrets.py - do not edit. Applied only when the indexer initialises a fresh security index.
_meta:
  type: "internalusers"
  config_version: 2

admin:
  hash: "{hashes['admin']}"
  reserved: true
  backend_roles:
  - "admin"
  description: "Indexer admin (Filebeat, dashboard server-side)"

kibanaserver:
  hash: "{hashes['kibanaserver']}"
  reserved: true
  description: "Wazuh dashboard server user"

{CC_READER}:
  hash: "{hashes[CC_READER]}"
  reserved: false
  backend_roles: []
  description: "Command center API + triage agent: read-only (role cc_read, mapped by scripts/indexer_roles.py)"
"""


def render_dashboard_wazuh_yml(api_password: str) -> str:
    """Pure: dashboard -> Wazuh API connection (same host id upstream uses, so the image's templating stays off)."""
    check_secret("WAZUH_API_PASS", api_password)
    return f"""# GENERATED by scripts/gen_secrets.py - do not edit.
hosts:
  - 1513629884013:
      url: "https://wazuh.manager"
      port: 55000
      username: wazuh-wui
      password: "{api_password}"
      run_as: true
"""


def bcrypt(password: str) -> str:
    """Hash with the installed indexer's own tool. The password travels in the child's environment, never argv."""
    if not os.path.isfile(HASH_TOOL):
        raise RuntimeError(f"{HASH_TOOL} not found: install the wazuh-indexer package first (Stage E1)")
    env = {**os.environ, "CC_PW": password, "JAVA_HOME": INDEXER_JDK}
    p = subprocess.run(["bash", HASH_TOOL, "-env", "CC_PW"], env=env, capture_output=True, text=True, timeout=180,
                       check=False)
    h = next((ln.strip() for ln in p.stdout.splitlines() if ln.strip().startswith("$2")), "")
    if p.returncode != 0 or not h:
        raise RuntimeError(f"hash.sh failed (rc={p.returncode}): {p.stderr.strip()[-300:]}")
    return h


def _write_mode(path: pathlib.Path, text: str, mode: int) -> None:
    """Atomic write whose temp file is created WITH `mode` (v4 first wrote .env.tmp world-readable, then chmod-ed)."""
    tmp = path.with_suffix(path.suffix + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    try:
        os.fchmod(fd, mode)
        os.write(fd, text.encode())
    finally:
        os.close(fd)
    tmp.replace(path)


def write_private(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    os.chmod(path.parent, 0o700)                  # host users cannot traverse; containers read via the bind mount
    _write_mode(path, text, 0o640)                # read by the wazuh-indexer / wazuh-dashboard service groups


def main() -> None:
    if not ENV.exists():
        sys.exit("[gen_secrets] .env missing: cp .env.example .env")
    text, changed = fill_env(ENV.read_text())
    if changed:
        _write_mode(ENV, text, 0o600)
        print(f"[gen_secrets] generated/updated in .env: {', '.join(changed)} (values not shown)")
    os.chmod(ENV, 0o600)
    env = parse_env(ENV.read_text())
    for k in SECRETS:
        check_secret(k, env[k])
    users = OUT / "internal_users.yml"
    hashes = {"admin": bcrypt(env["WAZUH_ADMIN_PASS"]),
              "kibanaserver": bcrypt(env["WAZUH_KIBANASERVER_PASS"]),
              CC_READER: bcrypt(env["INDEXER_PASS"])}
    write_private(users, render_internal_users(hashes))
    print(f"[gen_secrets] wrote {users.relative_to(ROOT)}")
    write_private(OUT / "wazuh.yml", render_dashboard_wazuh_yml(env["WAZUH_API_PASS"]))
    print(f"[gen_secrets] wrote {(OUT / 'wazuh.yml').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
